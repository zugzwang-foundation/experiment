import { cn } from "@/lib/utils";

import { c3OppositeSide } from "./composer/copy";
// ⚠ `Side` comes from `composer/gating`, NOT from `./types`. This file is a
// SHARED primitive — Discovery's `MarketCard` and `HeroPanels` are server
// components that render it — and `./types` re-exports the debate view-model's
// shape from `@/server/debate-view/**`. Both spellings are `"YES" | "NO"`, so
// taking the one that keeps this module's graph narrow costs nothing.
// `gating.ts` is pure decision logic over `@/server/config/limits`, itself a
// zero-import pure-data module with no `server-only` (the SG-6 law).
import { isEntryDisabled, type Side } from "./composer/gating";
import { formatPricePercent } from "./format";

/**
 * V29/V30 — the size presets. `hero` (22px bar, 12px labels) and `card` (16px,
 * 10.5px) are the `.barrow.f` / `.barrow.m` rows of
 * surface_discovery_v1_0.html (`:99-111`): LABEL — BAR — LABEL on one flex row,
 * gap 9px, no text inside the bar.
 *
 * ✅ HTML-FINISH · MARKET DETAIL round 2 · R7 — `detail` JOINS THE MAP AND
 * `D-J` IS DISCHARGED. It was the one preset with a structurally different
 * render (bar above, labels below) while d5's `/m/[slug]` bar is the SAME
 * one-row `.barrow` the Discovery ones are (`d5:505`, labels flanking the bar).
 * That divergence had been recorded and deliberately not actioned since
 * POLISH.3; round 1 built the change, measured it green, and backed it out
 * because the guard that pins `detail` sits OUTSIDE the task's allow-list. The
 * founder extended the allow-list by that ONE file on 2026-08-16.
 *
 * ⚠ THE NUMBERS DO NOT MOVE. `detail` keeps the 14px bar / 10px labels POLISH.3
 * applied from `d5:507-508` (`PD-3-01` / D5). Only the ARRANGEMENT changes, so
 * this row is composition, not a value.
 *
 * ⛔ `hero` AND `card` ARE UNREACHABLE FROM THIS CHANGE — they were already
 * generated by the shared return below and their entries here are byte-
 * unchanged. Their expectations in `price-bar-presets.test.tsx` are likewise
 * byte-identical; only `detail`'s baseline moved, which is the whole scope the
 * extended allow-list authorises.
 */
const ROW = {
	hero: { bar: "h-[22px]", label: "text-[12px]" },
	card: { bar: "h-[16px]", label: "text-[10.5px]" },
	detail: { bar: "h-[14px]", label: "text-[10px]" },
} as const;

/**
 * The market price bar (DEBATE.4 §5 / D1) — Yes%/No% from `getPrices`, pole-
 * coded: the YES proportion is the black (`--color-yes`) segment, the remainder
 * the white (`--color-no`) segment, delineated by a hairline so the bar shape
 * reads on the dark ground (the black YES segment ≡ ground collision is
 * accepted — adjacency + the track edge carry it, values-log v0_3 §1 item 8).
 * The percent is paired with literal text (AGENTS.md
 * §8 — never colour alone). `null` pricing (an unpooled market) → a quiet stub.
 *
 * `size` is REQUIRED and has no default: a missing required argument is a
 * compile error, a defaulted one is a silent wrong render (CLAUDE.md §8 O-1,
 * structural beats procedural).
 *
 * ⚠ The mockup's `.bar{border:1px solid var(--ink)}`, `.bar{background:
 * var(--n0)}` and `.fill{background:var(--ink)}` are DELIBERATELY NOT PORTED BY
 * NAME. The mockups are LIGHT-theme (`--ink:#0A0A0A`, `--n0:#FFFFFF`); this
 * build is inverted (`--color-ink:#fafafa`, `--color-n0:#212121`). The fill is
 * the YES side and the track is the NO side, so porting either by token name
 * would invert the pole — the identical defect C0's guard exists to prevent.
 * The two segments stay `bg-yes` / `bg-no` and the edge stays `--hairline`.
 */
export function PriceBar({
	pricing,
	size,
	pick,
}: {
	pricing: { yes: string; no: string } | null;
	size: "hero" | "card" | "detail";
	/**
	 * HTML-FINISH · MARKET DETAIL round 2 · R7 (row 8) — the `.blab.click`
	 * percent labels (`d5:1038`, `:1040`): clicking one opens the bet composer
	 * for that side, exactly as the colhead's `Buy` does (`pick('yes')` /
	 * `pick('no')` → d5's `openMod`). OMIT to render the labels as plain text,
	 * which is what both Discovery sites do.
	 *
	 * ⛔ THE VIEWER STATE IS REQUIRED TOGETHER WITH THE HANDLER, deliberately as
	 * ONE object — the same shape and the same reason as `AggregateFooter`'s
	 * `triggers`: a trigger without its F-3 gate is a control that invites a bet
	 * the viewer cannot place. This label opens the SAME composer as `Buy`, so
	 * it has to refuse in the same three cases (`!marketOpen`, `suspended`, the
	 * opposite pole for a holder) or it becomes a bypass around `SlotHeader`'s
	 * gate — `DebateView`'s `marketColumnBody` renders the composer off
	 * `openSide` alone and checks none of them itself.
	 */
	pick?: {
		heldSide: Side | null;
		marketOpen: boolean;
		suspended: boolean;
		onPick: (side: Side) => void;
	};
}) {
	if (!pricing) {
		return <p className="text-xs text-muted-foreground">Pricing unavailable</p>;
	}
	// PCT.ROUND: YES canonical, NO derived as 100 − YES — the pair always sums
	// to exactly 100 (SPEC.1 §10.8). The bar geometry below is unchanged.
	const yesPct = formatPricePercent(pricing, "YES");
	const noPct = formatPricePercent(pricing, "NO");

	const s = ROW[size];
	// `.blab` — 700, .05em, nowrap, `--ink`. `--ink` here is a text-EMPHASIS
	// token, not a side encoding: both labels carry it, so copying it by name is
	// the correct index-wise port (AGENTS.md §8).
	const label = `${s.label} font-bold tracking-[0.05em] whitespace-nowrap text-ink`;
	return (
		<div data-size={size} className="flex items-center gap-[9px]">
			<PriceLabel side="YES" pct={yesPct} className={label} pick={pick} />
			<div
				className={`${s.bar} flex flex-1 overflow-hidden rounded-[var(--r)] [border:var(--hairline)]`}
				role="img"
				aria-label={`YES ${yesPct}, NO ${noPct}`}
			>
				{/* Width is a data-driven length (the price proportion) — a string
				    percentage, not float math (CLAUDE.md §2). */}
				<div className="h-full bg-yes" style={{ width: yesPct }} />
				<div className="h-full flex-1 bg-no" />
			</div>
			<PriceLabel side="NO" pct={noPct} className={label} pick={pick} />
		</div>
	);
}

/**
 * One end of the bar — `.blab` (`d5:506`), optionally `.blab.click` (`:514-515`).
 *
 * ⛔ NO `aria-label` OVERRIDE, and that is WCAG 2.5.3 (Label in Name) rather
 * than an omission. The visible text is `YES 38%`, so any accessible name has to
 * CONTAIN that string — "Buy YES" does not, and "Buy YES — 38%" does not either
 * (the visible run is `YES 38%`, not `YES — 38%`). The affordance is carried by
 * `title` instead, which browsers surface as a tooltip WITHOUT displacing the
 * accessible name once the element has text content. ⚠ Contrast `SlotHeader`'s
 * entry, where `aria-label={`Buy ${side}`}` IS compliant because its visible
 * text is the single word `Buy`, which that label contains.
 *
 * ⚠ THE TEXT NODE IS IDENTICAL IN BOTH ARMS, so the bar reads the same whether
 * or not the viewer can act. Only the element type and the affordance change.
 *
 * ⚠ `.blab.click:hover{text-decoration:underline}` (`d5:515`) is d5's own hover
 * and it is STRUCTURE, not a value — `hover:underline` is already the shipped
 * class on every other navigating text element here (Profile's argument title,
 * the debate author pseudonym).
 */
function PriceLabel({
	side,
	pct,
	className,
	pick,
}: {
	side: Side;
	pct: string;
	className: string;
	pick?: {
		heldSide: Side | null;
		marketOpen: boolean;
		suspended: boolean;
		onPick: (side: Side) => void;
	};
}) {
	const text = `${side} ${pct}`;
	if (!pick) {
		return <span className={className}>{text}</span>;
	}
	const oppositeHeld = isEntryDisabled({
		resultingSide: side,
		heldSide: pick.heldSide,
	});
	const disabled = !pick.marketOpen || pick.suspended || oppositeHeld;
	// The same C3 batch string the colhead entry and the card pills carry, so one
	// refusal reads the same way wherever the viewer meets it.
	const c3 =
		oppositeHeld && pick.heldSide !== null
			? c3OppositeSide({ held: pick.heldSide, resulting: side })
			: null;
	return (
		<button
			type="button"
			data-testid={`price-label-${side}`}
			disabled={disabled}
			aria-disabled={disabled}
			title={c3 ?? `Buy ${side}`}
			onClick={() => pick.onPick(side)}
			className={cn(
				className,
				"rounded-(--r-chip) outline-none hover:underline focus-visible:shadow-(--state-focus-ring) disabled:pointer-events-none disabled:no-underline disabled:opacity-(--state-disabled-opacity)",
			)}
		>
			{text}
		</button>
	);
}
