/**
 * The environment contract for the Zugzwang AWS stacks.
 *
 * Every value that differs between staging and production lives here, so that
 * `lib/` contains no environment literals and `cdk diff` between the two is a
 * diff of this file. No secret VALUE ever appears in config — only the name of
 * the Secrets Manager secret and the JSON keys inside it.
 */

export interface HostedZoneConfig {
	/** Route 53 hosted zone id, when Route 53 owns the DNS. */
	readonly hostedZoneId: string;
	/** The zone apex, e.g. `zugzwangworld.com`. */
	readonly zoneName: string;
	/** The record to create, e.g. `staging.zugzwangworld.com`. */
	readonly recordName: string;
}

/**
 * The RDS PostgreSQL instance (AWS-MIGRATION-1 / ADR-0059).
 *
 * ⚠ NOTHING HERE IS A CREDENTIAL. The master password is generated by RDS into
 * a Secrets Manager secret at deploy time; this block only sizes the box and
 * says how carefully it is kept.
 */
export interface DatabaseConfig {
	/** RDS instance type WITHOUT the `db.` prefix, e.g. `t4g.small`. */
	readonly instanceType: string;
	/** Standby in the second AZ with automatic failover. */
	readonly multiAz: boolean;
	/** Initial gp3 volume, GiB. The dataset is under 1 MB; 20 is the RDS minimum. */
	readonly allocatedStorageGb: number;
	/** Storage autoscaling ceiling, GiB. A belt, not a plan. */
	readonly maxAllocatedStorageGb: number;
	/** Automated backup retention, days. Point-in-time recovery rides on this. */
	readonly backupRetentionDays: number;
	/** Refuse `DeleteDBInstance` until this is switched off first. */
	readonly deletionProtection: boolean;
	/** Master username. The password is generated, never configured. */
	readonly masterUsername: string;
}

export interface EnvironmentConfig {
	/** Short name used in stack ids and resource names: `staging` | `production`. */
	readonly name: string;
	/** The value the app reads as ZUGZWANG_ENV — `staging` | `prod`. */
	readonly zugzwangEnv: "staging" | "prod";
	/** AWS region. Supabase lives in ap-south-1, so compute belongs there too. */
	readonly region: string;
	/** AWS account id. Left undefined for an environment-agnostic synth. */
	readonly account?: string;
	/**
	 * CDK bootstrap qualifier (H-3). Each environment deploys through its OWN
	 * bootstrap roles, so a credential that can reach one environment's
	 * deploy/exec roles cannot reach the other's. Staging keeps the default
	 * `hnb659fds` (what it was bootstrapped with — changing it would re-point a
	 * running environment); production gets `zzprod`, bootstrapped separately
	 * with a scoped execution policy (docs/aws-migration/09-PRODUCTION-READINESS.md).
	 */
	readonly bootstrapQualifier: string;

	// ── Network ──────────────────────────────────────────────────────────────
	readonly vpcCidr: string;
	/**
	 * 0 → tasks run in public subnets with a public IP and no inbound rules
	 *     (cheapest; no NAT charge).
	 * 1 → tasks run in private subnets behind one NAT Gateway (~$32/month).
	 */
	readonly natGateways: number;

	// ── Compute ──────────────────────────────────────────────────────────────
	readonly containerPort: number;
	/** CPU units reserved for the task (1024 = one vCPU). */
	readonly cpu: number;
	/** Hard memory ceiling for the container, MiB. */
	readonly memoryMiB: number;
	/**
	 * SOFT memory reservation, MiB. On EC2 this is what ECS uses for placement,
	 * so keeping it well below `memoryMiB` is what lets the old task and the new
	 * one sit on the same instance for the few seconds of a rolling deploy.
	 */
	readonly memoryReservationMiB: number;
	/** EC2 instance type backing the ECS cluster, e.g. `t3.medium`. */
	readonly instanceType: string;
	/** ASG bounds. Min 1 keeps the app up; max 2 gives a deploy room to land. */
	readonly minInstances: number;
	readonly maxInstances: number;
	/** Image tag deployed by CI. Overridable at synth with `-c imageTag=...`. */
	readonly imageTag: string;
	readonly ecrRepositoryName: string;
	readonly desiredCount: number;
	/**
	 * ⚠ Next.js `cacheComponents` keeps its cache PER PROCESS, and
	 * `revalidateTag` from moderation reaches only the task that served the
	 * request. Until a shared cache handler exists, production must stay at 1.
	 */
	readonly maxCapacity: number;
	/** Seconds ECS waits after SIGTERM — must outlast in-flight `after()` work. */
	readonly stopTimeoutSeconds: number;
	/**
	 * V8 old-space ceiling for the app container, MiB — emitted as
	 * `NODE_OPTIONS=--max-old-space-size=<n>`. AWS-MIGRATION-3: the staging load
	 * test (08-STAGING-LOAD-TEST-RESULTS.md §3.3) found Node's own default (560 MB
	 * in a 1 GiB container) reached after ~1,500 bets, after which the process
	 * spent ~0.9 vCPU in garbage collection with no traffic and never recovered.
	 * Keep it at or below ~70 % of `memoryMiB`: the remainder is native memory,
	 * V8 metadata and buffers, and a heap set above the container limit is killed
	 * by ECS instead of thrashing.
	 */
	readonly nodeMaxOldSpaceMiB: number;
	/**
	 * Node `server.keepAliveTimeout`, ms — read by Next's standalone `server.js`
	 * from `KEEP_ALIVE_TIMEOUT`. MUST exceed the ALB idle timeout (60 s in
	 * compute-stack.ts): with Node's 5 s default the ALB reused sockets the
	 * target had just closed, a 0.1–0.5 % `HTTPCode_ELB_5XX` floor on every load
	 * level. `scripts/docker/server-timeouts.cjs` sets `headersTimeout` 5 s above it.
	 */
	readonly keepAliveTimeoutMs: number;
	/**
	 * Target-group health-check path. `/api/ready` (AWS-MIGRATION-3) answers 503
	 * until the process has rendered the home page and every Open market once,
	 * so a fresh task receives ALB traffic only after it is warm — a cold task
	 * collapsed under 12 concurrent users in the load test.
	 */
	readonly readinessPath: string;
	/** Seconds ECS ignores failing health checks after a task starts. */
	readonly healthCheckGracePeriodSeconds: number;
	/**
	 * The write-pause flag for the final production data sync. When set to the
	 * exact value `"paused"`, `proxy.ts` answers every write with 503 +
	 * Retry-After while reads continue. Deliberately a task environment value,
	 * never a secret: flipping it is a config change and a rolling restart.
	 */
	readonly writesPaused?: "paused";
	/** Enable ECS Exec for debugging. Off by default. */
	readonly enableExecuteCommand: boolean;

	// ── Ingress ──────────────────────────────────────────────────────────────
	/** ACM certificate in THIS region for the ALB. Undefined → HTTP-only listener. */
	readonly certificateArn?: string;
	/** Route 53 record to create. Undefined → DNS is managed elsewhere (Cloudflare). */
	readonly hostedZone?: HostedZoneConfig;
	/** Public base URL of the app; the cron rules call it. */
	readonly appBaseUrl: string;
	/** Put CloudFront in front of the ALB. Off when Cloudflare already fronts it. */
	readonly cloudFrontEnabled: boolean;
	/** Attach an AWS-managed WAF rule set to the ALB. */
	readonly wafEnabled: boolean;
	/**
	 * I — `count` logs what the managed rules WOULD block without blocking it;
	 * `block` enforces. A rule set nobody has watched against real traffic
	 * starts in `count`: its XSS / body-size rules can 403 a participant's
	 * argument, and a silent 403 on the bet path is worse than no WAF. Move to
	 * `block` only after the sampled requests from a rehearsal are read.
	 */
	readonly wafMode: "count" | "block";

	// ── Secrets ──────────────────────────────────────────────────────────────
	/** Secrets Manager secret NAME (created and populated outside CDK). */
	readonly secretName: string;
	/** JSON keys inside that secret, injected as container `secrets:`. */
	readonly secretKeys: readonly string[];
	/** JSON key holding the full cron header value, e.g. `Bearer <CRON_SECRET>`. */
	readonly cronAuthHeaderKey: string;

	// ── Database ─────────────────────────────────────────────────────────────
	/** The RDS PostgreSQL instance this environment owns (AWS-MIGRATION-1). */
	readonly database: DatabaseConfig;

	// ── Migrations ───────────────────────────────────────────────────────────
	/**
	 * Command for the one-off migration task. CI may run migrations itself
	 * instead; this task exists so migrations can also run inside the VPC.
	 */
	readonly migrationCommand: readonly string[];
	/**
	 * Secret JSON keys the MIGRATION task needs on top of `secretKeys`.
	 * `scripts/migrate-{staging,prod}.ts` deliberately read `DATABASE_URL_<ENV>`
	 * and `<ENV>_PROJECT_REF_FRAGMENT` — suffix-separated from `DATABASE_URL` so
	 * an env-confusion accident refuses rather than connects (ADR-0022). Without
	 * these the task starts, prints "DATABASE_URL_STAGING is not set" and exits 1.
	 */
	readonly migrationSecretKeys: readonly string[];

	// ── Observability ────────────────────────────────────────────────────────
	readonly logRetentionDays: number;
	/** Email subscribed to the alarm topic. Undefined → topic without subscribers. */
	readonly alertEmail?: string;
	readonly alarmThresholds: {
		readonly target5xxPerFiveMinutes: number;
		readonly p95LatencySeconds: number;
		readonly cpuPercent: number;
		readonly memoryPercent: number;
	};
}

/**
 * The ECS task roles' names, fixed rather than CloudFormation-generated so the
 * GitHub deploy role can `iam:PassRole` them by exact ARN (deploy-stack.ts).
 * One definition, read by both the stack that creates them and the one that
 * grants on them.
 */
export function taskRoleNames(environment: string): {
	execution: string;
	task: string;
} {
	return {
		execution: `zugzwang-${environment}-task-execution`,
		task: `zugzwang-${environment}-task`,
	};
}

/** A scheduled job, mapped 1:1 from `vercel.json` crons. */
export interface CronJob {
	readonly id: string;
	/** Path on the app, e.g. `/api/cron/close-due-markets`. */
	readonly path: string;
	/** EventBridge schedule expression. */
	readonly schedule: string;
	readonly description: string;
}

