/**
 * WARLI-FIELD-ASSET — emit the static field as a standalone SVG file.
 *
 *   pnpm art:field   # writes public/art/warli-field.<hash>.svg + field-asset.ts
 *
 * The auth layout's artwork is two rotating rings over a field that never
 * moves. Inline, the field was ~682 KB of every auth page's HTML; as a file it
 * is fetched once. `hero.tsx` paints it as its own CSS background
 * (`FIELD_ASSET_HREF`). The explicit `width`/`height` give the file an
 * intrinsic size, so `background-size: cover` resolves it the same way the
 * hero's `xMidYMid slice` resolves the rings.
 *
 * ⚠ IT RENDERS THE REAL COMPONENT. The drawing below is
 * `renderToStaticMarkup(<FieldLayer />)`, so `field-layer.tsx` stays the source
 * of truth and this file is a build product of it.
 * `tests/unit/art/field-asset.test.ts` calls `buildFieldSvg()` and fails if the
 * committed file differs, which is what stops an edit to the field shipping a
 * stale picture.
 *
 * ⚠ THE TWO COLOURS ARE READ FROM `src/app/globals.css`, NOT WRITTEN HERE. An
 * SVG loaded as an image is a separate document and cannot see the page's
 * custom properties, so the hero's `color: var(--color-ink)` and
 * `.warli-reserve { color: var(--color-ground) }` have to be resolved to values
 * inside the file. Reading them keeps the token pins in
 * `tests/unit/design/tokens-monochrome.test.ts` the only place those values
 * are stated.
 *
 * ⚠ THE FILENAME CARRIES A HASH OF ITS OWN CONTENT, AND THAT IS WHAT MAKES THE
 * LONG CACHE SAFE. `next.config.ts` serves `/art/warli-field.<hash>.svg` as
 * `immutable` for a year, so a browser that has it never asks again. That is
 * only correct if a changed drawing gets a NEW URL — so the hash is computed
 * here, stale files are deleted, and the URL the hero uses is written into
 * `src/components/art/warli/field-asset.ts` rather than typed by hand.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { renderToStaticMarkup } from "react-dom/server";

import { FieldLayer } from "../src/components/art/warli/field-layer";
import { VIEW_HEIGHT, VIEW_WIDTH } from "../src/components/art/warli/hero";

export const FIELD_ASSET_DIR = "public/art";
export const FIELD_ASSET_MODULE = "src/components/art/warli/field-asset.ts";

function token(css: string, name: string): string {
	const match = css.match(new RegExp(`${name}:\\s*(#[0-9a-f]{6})\\s*;`, "i"));
	if (match?.[1] === undefined) {
		throw new Error(`warli-field-svg: ${name} not found in globals.css`);
	}
	return match[1];
}

export function buildFieldSvg(root: string = process.cwd()): string {
	const css = readFileSync(join(root, "src/app/globals.css"), "utf8");
	const ink = token(css, "--color-ink");
	const ground = token(css, "--color-ground");
	const field = renderToStaticMarkup(<FieldLayer />);
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${VIEW_WIDTH}" height="${VIEW_HEIGHT}" viewBox="0 0 ${VIEW_WIDTH} ${VIEW_HEIGHT}" fill="none" stroke="currentColor"><style>svg{color:${ink}}.warli-reserve{color:${ground}}</style>${field}</svg>\n`;
}

/** `/art/warli-field.<first 10 hex of sha256>.svg` for this exact content. */
export function fieldAssetHref(svg: string): string {
	const hash = createHash("sha256").update(svg).digest("hex").slice(0, 10);
	return `/art/warli-field.${hash}.svg`;
}

/** The generated module's full text. Biome-clean as written. */
export function fieldAssetModule(href: string): string {
	return [
		"// GENERATED by scripts/warli-field-svg.tsx (`pnpm art:field`). Do not hand-edit.",
		"// The hash is of the file's content, so a changed drawing is a new URL and the",
		"// year-long immutable cache in next.config.ts can never serve a stale field.",
		`export const FIELD_ASSET_HREF = "${href}";`,
		"",
	].join("\n");
}

if (process.argv.includes("--write")) {
	const root = process.cwd();
	const svg = buildFieldSvg(root);
	const href = fieldAssetHref(svg);
	const dir = join(root, FIELD_ASSET_DIR);
	// Stale hashes go, so exactly one field file is ever published.
	for (const name of readdirSync(dir)) {
		if (name.startsWith("warli-field") && name.endsWith(".svg")) {
			rmSync(join(dir, name));
		}
	}
	writeFileSync(join(root, "public", href), svg, "utf8");
	writeFileSync(join(root, FIELD_ASSET_MODULE), fieldAssetModule(href), "utf8");
	console.log(`wrote public${href} (${Buffer.byteLength(svg)} bytes)`);
}
