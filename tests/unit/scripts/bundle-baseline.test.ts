import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import type { BundleReport } from "../../../scripts/measure-frontend-bundle";

const SRC_ROOT = join(process.cwd(), "src");

/** Every `.ts`/`.tsx` file under `src/`, as repo-relative forward-slash paths. */
function sourceFiles(): string[] {
	return readdirSync(SRC_ROOT, { recursive: true, withFileTypes: true })
		.filter(
			(e) => e.isFile() && (e.name.endsWith(".ts") || e.name.endsWith(".tsx")),
		)
		.map((e) => join(e.parentPath, e.name));
}

// HO-T4 D2 — the pinned baseline.
//
// THE WEAK FORM, STATED PLAINLY (per the brief's own instruction not to oversell
// this): `.github/workflows/ci.yml` does not run `next build` anywhere — grepped
// directly, confirmed absent. So this cannot assert against a live build in CI;
// it asserts only the SHAPE and CEILINGS of the committed
// `scripts/bundle-baseline.json`, regenerated by running
// `pnpm exec next build && just bundle-report` and committed alongside whatever
// code change it measures. That means this guard catches someone hand-editing
// the JSON to something absurd, or a genuine regression IF AND ONLY IF the
// author re-ran the script and committed the new number — it does NOT
// independently re-verify the number against a real build the way
// `tests/unit/db/client-options.test.ts` verifies a module-load side effect
// every run. Pattern followed is still that file's: pin the VALUE, not a
// derivation of it, and say in prose exactly what property is being protected.
//
// CEILING, NOT EQUALITY, PER THE BRIEF: `measured <= ceiling`, never
// `measured === baseline`. A zero-headroom pin reddens on every other lane's
// merge and becomes noise inside a week. Headroom chosen: baseline + 5%,
// applied uniformly below — generous enough that routine, unrelated churn
// elsewhere in a shared chunk doesn't false-positive this file, tight enough
// that a genuine regression (a new eagerly-loaded dependency, an accidentally
// un-split component) still trips it. THIS IS A RATCHET: a future task that
// measurably shrinks one of these numbers must lower its ceiling in the same
// PR, not leave slack for the old, larger number to creep back into.
//
// Numbers below are what `scripts/bundle-baseline.json` held when this test was
// written (`main` @ `4c67f30`, 2026-08-31). If a later run's numbers differ,
// that is a FINDING to report, not a mismatch to silently reconcile — same rule
// D2 states for the script's own reference table.

const BASELINE_PATH = join(process.cwd(), "scripts", "bundle-baseline.json");

function readBaseline(): BundleReport {
	return JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as BundleReport;
}

function routeOf(report: BundleReport, route: string) {
	const entry = report.routes.find((r) => r.route === route);
	if (!entry) {
		throw new Error(
			`route "${route}" not present in scripts/bundle-baseline.json — ` +
				"re-run the script; a route this test pins has disappeared from the build.",
		);
	}
	return entry;
}

describe("frontend bundle baseline — scripts/bundle-baseline.json (HO-T4 D2)", () => {
	it("bundle-baseline::artifact-has-the-expected-shape", () => {
		const report = readBaseline();
		expect(typeof report.measuredAt).toBe("string");
		expect(typeof report.sharedRawBytes).toBe("number");
		expect(typeof report.sharedGzipBytes).toBe("number");
		expect(typeof report.largestSharedChunkRawBytes).toBe("number");
		expect(Array.isArray(report.routes)).toBe(true);
		expect(report.routes.length).toBeGreaterThan(0);
	});

	// R3 RE-PIN, AND THE REASON FOR EACH NUMBER THAT MOVED.
	//
	// Every ceiling below was re-measured after `measure-frontend-bundle.ts` was
	// corrected to read Turbopack's `entryJSFiles` instead of the webpack
	// `clientModules` fallback. The correction alone adds exactly one 4,600 B
	// chunk to every route that has client modules at all, so a bare "the numbers
	// went up" would have hidden real growth inside a mechanical correction.
	// Split, so neither hides the other:
	//
	//   route                committed    measured   delta   correction   drift
	//   /                      222,076     227,237   +5,161      +4,600    +561
	//   /m/[slug]              291,957     298,355   +6,398      +4,600  +1,798
	//   /u/[pseudonym]         219,047     223,647   +4,600      +4,600       0
	//   /onboarding            220,315     224,915   +4,600      +4,600       0
	//   /sign-in               245,173     249,773   +4,600      +4,600       0
	//   /sign-in/otp           245,188     249,788   +4,600      +4,600       0
	//   /legal                 155,777     160,377   +4,600      +4,600       0
	//   /admin/moderation       63,741      68,341   +4,600      +4,600       0
	//   /admin/markets          26,393      30,993   +4,600      +4,600       0
	//   /admin/markets/[id]     30,556      35,156   +4,600      +4,600       0
	//   sharedRawBytes         993,244     993,244       +0           0       0
	//
	// ⚠ TWO ROUTES CARRY REAL DRIFT AND IT IS NOT THIS TASK'S: `/` +561 B and
	// `/m/[slug]` +1,798 B beyond the correction. They are named here rather than
	// absorbed silently, because the previous regeneration swallowed 102 commits
	// of growth without an owner and this file's own header forbids exactly that.
	//
	// ⚠ `/m/[slug]` was ALREADY 392 B over its old ceiling before any of this —
	// and this suite was GREEN, because it asserts the committed artifact rather
	// than a live build. That is the second defect R3 records: a pin that cannot
	// fire until somebody regenerates, and nothing obliges anybody to. The
	// re-pin below does not fix it; only measuring the tree would.
	it("bundle-baseline::shared-chunks-stay-under-ceiling (baseline 993,244 B +5%, re-pinned at R3)", () => {
		const report = readBaseline();
		expect(report.sharedRawBytes).toBeLessThanOrEqual(1_042_906);
	});

	it("bundle-baseline::shared-chunks-gzip-stays-under-ceiling (baseline 311,253 B +5%, re-pinned at R3)", () => {
		const report = readBaseline();
		expect(report.sharedGzipBytes).toBeLessThanOrEqual(326_815);
	});

	it("bundle-baseline::discovery-route-own-bytes-under-ceiling (baseline 227,237 B +5%, re-pinned at R3)", () => {
		const report = readBaseline();
		expect(routeOf(report, "/").ownRawBytes).toBeLessThanOrEqual(238_598);
	});

	it("bundle-baseline::debate-view-route-own-bytes-under-ceiling (baseline 298,355 B +5%, re-pinned at R3)", () => {
		// The route T5 exists to shrink. Its ceiling is the one this repo most
		// wants a future PR to LOWER, deliberately, as the ratchet this file's
		// header describes — not a number to defend as-is.
		const report = readBaseline();
		expect(routeOf(report, "/m/[slug]").ownRawBytes).toBeLessThanOrEqual(
			313_272,
		);
	});

	it("bundle-baseline::profile-route-own-bytes-under-ceiling (baseline 223,647 B +5%, re-pinned at R3)", () => {
		const report = readBaseline();
		// Lowered from 252_804 B at T5 when PositionsTable dynamic split landed (-22 KiB win).
		expect(routeOf(report, "/u/[pseudonym]").ownRawBytes).toBeLessThanOrEqual(
			234_829,
		);
	});

	it("bundle-baseline::next-dynamic-allowed-at-sanctioned-sites", () => {
		// T5 (HO-FINISH §6) landed the first sanctioned dynamic boundary at
		// `src/components/profile/ProfileArena.tsx` (PositionsTable, saving ~22 KiB).
		// Any OTHER dynamic boundary still triggers this guard loudly so that
		// wrapper costs are measured before shipping.
		const SANCTIONED = new Set([
			join(SRC_ROOT, "components", "profile", "ProfileArena.tsx"),
		]);
		const offenders = sourceFiles().filter((path) => {
			if (SANCTIONED.has(path)) return false;
			const src = readFileSync(path, "utf8");
			return /\bnext\/dynamic\b/.test(src) || /\bReact\.lazy\s*\(/.test(src);
		});
		expect(offenders).toEqual([]);
	});
});
